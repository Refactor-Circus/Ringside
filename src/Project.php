<?php

declare(strict_types=1);

namespace RefactorCircus\Ringside;

use RuntimeException;

/**
 * The consuming package: its root, its vendor dir and its ring-master.yml.
 * Every path ringside writes is relative to this root.
 */
final readonly class Project
{
    public const string GENERATED_MARKER = 'generated by ringside';

    public Config $config;

    public string $vendorDir;

    public function __construct(public string $root)
    {
        $this->config = Config::load($root);
        $this->vendorDir = self::vendorDir($root);
    }

    public static function find(string $from): self
    {
        $dir = $from;

        while (! is_file($dir.'/composer.json')) {
            $parent = dirname($dir);

            if ($parent === $dir) {
                throw new RuntimeException("No composer.json found above {$from}.");
            }

            $dir = $parent;
        }

        return new self($dir);
    }

    public function path(string $relative = ''): string
    {
        return $relative === '' ? $this->root : $this->root.'/'.ltrim($relative, '/');
    }

    public function agentPath(string $relative = ''): string
    {
        $dir = $this->config->agentDir();

        return $relative === '' ? $dir : $dir.'/'.ltrim($relative, '/');
    }

    public function exists(string $relative): bool
    {
        return file_exists($this->path($relative));
    }

    public function read(string $relative): ?string
    {
        $file = $this->path($relative);

        return is_file($file) ? (string) file_get_contents($file) : null;
    }

    /**
     * Writes only when the content changed, so unchanged files keep their mtime.
     */
    public function write(string $relative, string $contents): bool
    {
        if ($this->read($relative) === $contents) {
            return false;
        }

        $file = $this->path($relative);

        if (! is_dir(dirname($file))) {
            mkdir(dirname($file), 0o755, true);
        }

        file_put_contents($file, $contents);

        return true;
    }

    public function isGenerated(string $relative): bool
    {
        return str_contains((string) $this->read($relative), self::GENERATED_MARKER);
    }

    private static function vendorDir(string $root): string
    {
        $manifest = json_decode((string) file_get_contents($root.'/composer.json'), true);
        $dir = is_array($manifest) ? ($manifest['config']['vendor-dir'] ?? 'vendor') : 'vendor';

        return trim(is_string($dir) ? $dir : 'vendor', '/');
    }
}
