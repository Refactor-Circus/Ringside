<?php

declare(strict_types=1);

namespace RefactorCircus\Ringside\Standards;

use Symfony\Component\Yaml\Yaml;

final readonly class Resolution
{
    /**
     * @param  list<Layer>  $layers
     * @param  array<string, Standard>  $standards
     * @param  array<string, list<string>>  $paths
     * @param  list<string>  $missing  configured global packages that are not installed
     */
    public function __construct(
        public array $layers,
        public array $standards,
        public array $paths,
        public string $fingerprint,
        public array $missing = [],
    ) {}

    /**
     * @return array<string, list<Standard>>
     */
    public function byCategory(): array
    {
        $categories = [];

        foreach ($this->standards as $standard) {
            $categories[$standard->category()][] = $standard;
        }

        ksort($categories);

        return $categories;
    }

    /**
     * @return list<Layer>
     */
    public function packageLayers(): array
    {
        return array_values(array_filter($this->layers, static fn (Layer $layer): bool => $layer->package !== null));
    }

    public function toYaml(): string
    {
        $standards = array_map(static fn (Standard $standard): array => $standard->toIndex(), $this->standards);

        return "# generated by ringside; do not edit. Rebuild with: vendor/bin/ringside sync\n"
            .Yaml::dump(['fingerprint' => $this->fingerprint, 'standards' => $standards], 4, 2, Yaml::DUMP_EMPTY_ARRAY_AS_SEQUENCE);
    }

    public static function storedFingerprint(?string $index): ?string
    {
        return $index !== null && preg_match('/^fingerprint:\s*\'?([0-9a-f]+)/m', $index, $matches) ? $matches[1] : null;
    }
}
