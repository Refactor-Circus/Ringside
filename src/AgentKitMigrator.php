<?php

declare(strict_types=1);

namespace RefactorCircus\Ringside;

use FilesystemIterator;
use RefactorCircus\Ringside\Render\ManagedBlock;
use RefactorCircus\Ringside\Standards\StandardsResolver;
use stdClass;

/**
 * Moves an agent-kit install (Ring Master's predecessor) to the Ring Master
 * names: config file, jobs folder, AGENTS.md markers, .gitignore lines, and
 * removes the old generated skills, agents and hooks so the next sync
 * writes the new ones. Hand-written files are never deleted.
 */
final class AgentKitMigrator
{
    public const string LEGACY_CONFIG = 'agent-kit.yml';

    public const string LEGACY_JOBS = '.agent-kit';

    private const string LEGACY_MARKER = 'generated by agent-kit';

    private const string LEGACY_PACKAGE = 'refactor-circus/agent-kit';

    public function needed(Project $project): bool
    {
        return $project->exists(self::LEGACY_CONFIG)
            || is_dir($project->path(self::LEGACY_JOBS))
            || $this->generated($project) !== []
            || str_contains((string) $project->read('AGENTS.md'), '<!-- agent-kit:start -->')
            || str_contains((string) $project->read('.claude/settings.json'), 'agent-kit-hook');
    }

    /**
     * @return list<string> one line per action, prefixed "Would" when dry
     */
    public function migrate(Project $project, bool $dryRun = false): array
    {
        $log = [];
        $do = static fn (string $done, string $would): string => $dryRun ? $would : $done;

        if ($project->exists(self::LEGACY_CONFIG)) {
            if ($project->exists(Config::FILE)) {
                $log[] = 'Kept '.self::LEGACY_CONFIG.': '.Config::FILE.' already exists; merge it by hand and delete it.';
            } else {
                $log[] = $do('Renamed ', 'Would rename ').self::LEGACY_CONFIG.' to '.Config::FILE;

                if (! $dryRun) {
                    $contents = (string) $project->read(self::LEGACY_CONFIG);
                    $project->write(Config::FILE, strtr($contents, [self::LEGACY_JOBS.'/' => '.ring-master/', 'agent-kit configuration' => 'Ring Master configuration', 'vendor/'.self::LEGACY_PACKAGE.'/' => 'vendor/'.StandardsResolver::PACKAGE.'/']));
                    unlink($project->path(self::LEGACY_CONFIG));
                }
            }
        }

        if (is_dir($project->path(self::LEGACY_JOBS))) {
            $log[] = $this->jobs($project, $dryRun);
        }

        foreach ($this->generated($project) as $path) {
            $log[] = $do('Deleted ', 'Would delete ').$path;

            if (! $dryRun) {
                is_dir($project->path($path)) ? Migrator::removeTree($project->path($path)) : unlink($project->path($path));
            }
        }

        $log = [...$log, ...$this->hooks($project, $dryRun), ...$this->markers($project, $dryRun), ...$this->gitignore($project, $dryRun)];

        $manifest = (string) $project->read('composer.json');

        if (str_contains($manifest, '"'.self::LEGACY_PACKAGE.'"')) {
            $log[] = 'composer.json still requires '.self::LEGACY_PACKAGE.'; remove it (composer remove --dev '.self::LEGACY_PACKAGE.') now that '.StandardsResolver::PACKAGE.' replaces it.';
        }

        return $log;
    }

    /**
     * The job folder holds git worktrees, which git tracks by path, so it
     * only moves once no job is left in it.
     */
    private function jobs(Project $project, bool $dryRun): string
    {
        $jobs = $project->path(self::LEGACY_JOBS.'/jobs');
        $left = is_dir($jobs) ? iterator_count(new FilesystemIterator($jobs)) : 0;

        if ($left > 0) {
            return 'Kept '.self::LEGACY_JOBS.'/: '.$left.' job folder(s) still in it; finish or clean them up (git worktree remove), then run migrate again.';
        }

        if (is_dir($project->path('.ring-master'))) {
            if (! $dryRun) {
                Migrator::removeTree($project->path(self::LEGACY_JOBS));
            }

            return ($dryRun ? 'Would delete ' : 'Deleted ').self::LEGACY_JOBS.'/ (empty; .ring-master/ already exists)';
        }

        if (! $dryRun) {
            rename($project->path(self::LEGACY_JOBS), $project->path('.ring-master'));
        }

        return ($dryRun ? 'Would rename ' : 'Renamed ').self::LEGACY_JOBS.'/ to .ring-master/';
    }

    /**
     * Generated agent-kit skills and agents, found by their marker so a
     * hand-written file with a similar name survives.
     *
     * @return list<string>
     */
    private function generated(Project $project): array
    {
        $found = [];

        foreach (self::claudeDirs($project) as $dir) {
            foreach (glob($project->path($dir.'/skills/agent-kit-*'), GLOB_ONLYDIR) ?: [] as $skill) {
                if (is_file($skill.'/SKILL.md') && str_contains((string) file_get_contents($skill.'/SKILL.md'), self::LEGACY_MARKER)) {
                    $found[] = $dir.'/skills/'.basename($skill);
                }
            }

            foreach (glob($project->path($dir.'/agents/agent-kit-*.md')) ?: [] as $agent) {
                if (str_contains((string) file_get_contents($agent), self::LEGACY_MARKER)) {
                    $found[] = $dir.'/agents/'.basename($agent);
                }
            }
        }

        return $found;
    }

    /**
     * @return list<string>
     */
    private function hooks(Project $project, bool $dryRun): array
    {
        $file = '.claude/settings.json';
        $settings = json_decode((string) $project->read($file), true);

        if (! is_array($settings) || ! is_array($settings['hooks'] ?? null)) {
            return [];
        }

        $removed = 0;

        foreach ($settings['hooks'] as $event => $entries) {
            $kept = array_values(array_filter(is_array($entries) ? $entries : [], static fn (mixed $entry): bool => ! str_contains((string) json_encode($entry), 'agent-kit-hook')));
            $removed += (is_array($entries) ? count($entries) : 0) - count($kept);
            $settings['hooks'][$event] = $kept;
        }

        if ($removed === 0) {
            return [];
        }

        $settings['hooks'] = array_filter($settings['hooks'], static fn (mixed $entries): bool => $entries !== []);

        if ($settings['hooks'] === []) {
            unset($settings['hooks']);
        }

        if (! $dryRun) {
            $project->write($file, json_encode($settings === [] ? new stdClass : $settings, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n");
        }

        return [($dryRun ? 'Would remove ' : 'Removed ').$removed.' agent-kit hook(s) from '.$file];
    }

    /**
     * @return list<string>
     */
    private function markers(Project $project, bool $dryRun): array
    {
        $log = [];
        $seen = [];

        foreach (['AGENTS.md', 'CLAUDE.md'] as $file) {
            $real = realpath($project->path($file));
            $contents = (string) $project->read($file);

            if ($real === false || isset($seen[$real]) || ! str_contains($contents, '<!-- agent-kit:start -->')) {
                continue;
            }

            $seen[$real] = true;
            $log[] = ($dryRun ? 'Would rename ' : 'Renamed ').'the agent-kit block markers in '.$file;

            if (! $dryRun) {
                $project->write($file, strtr($contents, ['<!-- agent-kit:start -->' => ManagedBlock::START, '<!-- agent-kit:end -->' => ManagedBlock::END]));
            }
        }

        return $log;
    }

    /**
     * @return list<string>
     */
    private function gitignore(Project $project, bool $dryRun): array
    {
        $contents = (string) $project->read('.gitignore');
        $updated = strtr($contents, [
            '# agent-kit generated files' => '# ringside generated files',
            '/agent-kit-*' => '/ring-master-*',
            self::LEGACY_JOBS => '.ring-master',
        ]);

        if ($updated === $contents) {
            return [];
        }

        if (! $dryRun) {
            $project->write('.gitignore', $updated);
        }

        return [($dryRun ? 'Would update ' : 'Updated ').'the agent-kit lines in .gitignore'];
    }

    /**
     * @return list<string>
     */
    private static function claudeDirs(Project $project): array
    {
        $dirs = ['.claude'];
        $link = $project->path('.claude');

        if (is_link($link)) {
            $target = trim(str_replace('\\', '/', (string) readlink($link)), '/');
            $dirs = $target === '' || str_contains($target, '/') ? $dirs : [$target];
        }

        return $dirs;
    }
}
