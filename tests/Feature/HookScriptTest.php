<?php

declare(strict_types=1);

use RefactorCircus\Ringside\Sync;

function runHook(string $root, string $event, string $stdin = ''): string
{
    $process = proc_open(
        [PHP_BINARY, dirname(__DIR__, 2).'/bin/ringside-hook', $event],
        [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']],
        $pipes,
        $root,
        ['CLAUDE_PROJECT_DIR' => $root, 'PATH' => (string) getenv('PATH')],
    );

    fwrite($pipes[0], $stdin);
    fclose($pipes[0]);
    $output = (string) stream_get_contents($pipes[1]);
    fclose($pipes[1]);
    fclose($pipes[2]);

    expect(proc_close($process))->toBe(0);

    return $output;
}

it('prints the summary and in-progress specs at session start', function () {
    $project = fixtureProject(['docs/agent/specs/2026-10-23-1430-import/meta.yml' => "status: in-progress\n"]);
    (new Sync)->run($project);

    expect(runHook($project->root, 'session-start'))
        ->toContain('ringside: 2 standards', 'In-progress: docs/agent/specs/2026-10-23-1430-import/')
        ->not->toContain('generated by');
});

it('adds RingMaster\'s queue line when an app is configured', function () {
    $app = fixtureProject(['artisan' => "<?php\nif ((\$argv[1] ?? '') === 'ring-master:summary') { echo 'RingMaster: 2 queued for '.substr(\$argv[2], 10).\"\\n\"; }\n"]);
    $project = withConfig(fixtureProject(), "board: { app: {$app->root} }\n");
    (new Sync)->run($project);

    expect(runHook($project->root, 'session-start'))
        ->toContain('ringside: 2 standards', 'RingMaster: 2 queued for '.$project->root)
        ->not->toContain('ring-master-app');
});

it('asks for a sync when there is no summary yet', function () {
    expect(runHook(fixtureProject()->root, 'session-start'))->toContain('run vendor/bin/ringside sync');
});

it('formats only php files inside the project and outside vendor', function () {
    $project = fixtureProject([
        'vendor/bin/pint' => "<?php file_put_contents(__DIR__.'/../../formatted.txt', \$argv[1].\"\\n\", FILE_APPEND);\n",
        'src/A.php' => "<?php\n",
        'README.md' => "# readme\n",
    ]);

    foreach (['src/A.php', 'README.md', 'vendor/x/B.php', '../elsewhere/C.php'] as $file) {
        runHook($project->root, 'post-edit', json_encode(['tool_input' => ['file_path' => $project->root.'/'.$file]]));
    }

    expect($project->read('formatted.txt'))->toBe($project->root."/src/A.php\n");
})->skipOnWindows();

it('formats with the nearest package\'s own tool in a workspace of packages', function () {
    $workspace = fixtureProject();
    writeFixture($workspace->root, 'Atrium/composer.json', '{}');
    writeFixture($workspace->root, 'Atrium/vendor/bin/pint', "<?php file_put_contents(getcwd().'/ran.txt', 'atrium');\n");
    writeFixture($workspace->root, 'Atrium/src/A.php', "<?php\n");

    runHook($workspace->root, 'post-edit', json_encode(['tool_input' => ['file_path' => $workspace->root.'/Atrium/src/A.php']]));

    expect($workspace->read('Atrium/ran.txt'))->toBe('atrium');
})->skipOnWindows();
